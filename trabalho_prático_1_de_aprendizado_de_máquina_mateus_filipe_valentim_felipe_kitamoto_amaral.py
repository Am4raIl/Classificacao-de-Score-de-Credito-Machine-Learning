def grid_search(
    pipelines,
    param_grids,
    colunas_treino,
    rotulos_treino,
    colunas_reais,
    rotulos_reais,
    cv_splits=2
):

    resultados = {}
    cv = StratifiedKFold(n_splits=cv_splits, shuffle=True, random_state=42)

    for nome, pipeline in pipelines.items():
        print(f"\n=== GridSearchCV para {nome} ===")
        param_grid = param_grids[nome]

        grid_resultados = GridSearchCV(
            estimator=pipeline,
            param_grid=param_grid,
            cv=cv,
            scoring='accuracy',
            n_jobs=1,
            verbose=3
        )
        grid_resultados.fit(colunas_treino, rotulos_treino)
        melhor_modelo = grid_resultados.best_estimator_
        rotulos_predito = melhor_modelo.predict(colunas_reais)

        print(f"\nMelhores parâmetros para {nome}: {grid_resultados.best_params_}")
        metricas = definir_metricas(rotulos_reais, rotulos_predito)

        resultados[nome] = {
            'modelo': melhor_modelo,
            'best_params': grid_resultados.best_params_,
            'metrics':  metricas
        }

    return resultados

