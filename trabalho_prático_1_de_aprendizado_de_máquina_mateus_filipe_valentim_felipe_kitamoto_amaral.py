def definir_metricas(rotulo_real, rotulo_predito):
  print(f"Acurácia: {accuracy_score(rotulo_real, rotulo_predito):.4f}")
  print(f"Precisão: {precision_score(rotulo_real, rotulo_predito, average='weighted'):.4f}")
  print(f"Recall: {recall_score(rotulo_real, rotulo_predito, average='weighted'):.4f}")
  print(f"F1-score: {f1_score(rotulo_real, rotulo_predito, average='weighted'):.4f}")
  return {
                'accuracia': accuracy_score(rotulo_real, rotulo_predito),
                'precisao': precision_score(rotulo_real, rotulo_predito, average='weighted'),
                'recall': recall_score(rotulo_real, rotulo_predito, average='weighted'),
                'f1': f1_score(rotulo_real, rotulo_predito, average='weighted')
          }

